#!/usr/bin/env node
/**
 * Registry Builder
 *
 * skills-registry.json 과 commands-registry.json 을 파일 시스템에서 자동 생성.
 * agents-registry.json 은 수동 유지 (현 관습 존중) — 스킬/커맨드는 수량이 많아 자동화.
 *
 * 실행: node .claude/scripts/build-registries.js
 * 산출: .claude/skills-registry.json, .claude/commands-registry.json
 * 검증: .claude/tests/catalog-integrity.sh 가 레지스트리 stats 를 실측과 대조.
 */

"use strict";

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "../..");
const SKILLS_DIR = path.join(ROOT, ".claude/skills");
const COMMANDS_DIR = path.join(ROOT, ".claude/commands");
const SKILL_RULES = path.join(ROOT, ".claude/skill-rules.json");

/**
 * 간이 YAML frontmatter 파서.
 * ---\nkey: value\n---\n 블록만 처리. 중첩/배열 미지원.
 */
function parseFrontmatter(content) {
  const m = content.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!m) return null;
  const result = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^([\w-]+):\s*(.*)$/);
    if (!kv) continue;
    let val = kv[2].trim();
    val = val.replace(/^["']|["']$/g, "");
    if (val === "true") val = true;
    else if (val === "false") val = false;
    result[kv[1]] = val;
  }
  return result;
}

/**
 * Command 파일의 설명 추출 — frontmatter.description 우선, fallback 은 첫 H1.
 */
function extractCommandMeta(content) {
  const fm = parseFrontmatter(content);
  if (fm && fm.description) {
    return {
      description: fm.description,
      allowedTools: fm["allowed-tools"] || null,
    };
  }
  const h1 = content.match(/^#\s+\/?([\w-]+)\s*[-—]\s*(.+)$/m);
  if (h1) {
    return { description: h1[2].trim(), allowedTools: null };
  }
  return { description: "", allowedTools: null };
}

/**
 * 도메인 카테고리 휴리스틱 (SKILLS.md 그룹핑과 일치)
 */
function categorizeSkill(name) {
  if (
    [
      "legacy-compliance-checker",
      "checklist-generator",
      "code-simplifier",
    ].includes(name)
  ) {
    return "common";
  }
  if (["kiips-stitch-bridge", "kiips-page-harness"].includes(name)) {
    return "design";
  }
  return "domain";
}

// ─── Skills Registry 생성 ─────────────────────────────────────
function buildSkillsRegistry() {
  const skillRules = fs.existsSync(SKILL_RULES)
    ? JSON.parse(fs.readFileSync(SKILL_RULES, "utf8"))
    : {};

  const skills = {};
  const categoryCounts = { domain: 0, common: 0, design: 0 };

  const entries = fs
    .readdirSync(SKILLS_DIR, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();

  for (const name of entries) {
    const skillFile = path.join(SKILLS_DIR, name, "SKILL.md");
    if (!fs.existsSync(skillFile)) continue;
    const content = fs.readFileSync(skillFile, "utf8");
    const fm = parseFrontmatter(content);
    if (!fm) continue;

    const category = categorizeSkill(name);
    categoryCounts[category]++;

    skills[name] = {
      file: path.relative(ROOT, skillFile),
      description: fm.description || "",
      disableModelInvocation: fm["disable-model-invocation"] === true,
      category,
      trigger: skillRules[name] || null,
    };
  }

  return {
    _generated: new Date().toISOString(),
    _description:
      "KiiPS skills registry. Auto-generated by .claude/scripts/build-registries.js",
    _source: ".claude/skills/*/SKILL.md frontmatter + .claude/skill-rules.json",
    skills,
    stats: {
      totalSkills: Object.keys(skills).length,
      domain: categoryCounts.domain,
      common: categoryCounts.common,
      design: categoryCounts.design,
    },
  };
}

// ─── Commands Registry 생성 ────────────────────────────────────
function buildCommandsRegistry() {
  const commands = {};

  const files = fs
    .readdirSync(COMMANDS_DIR)
    .filter((f) => f.endsWith(".md"))
    .sort();

  for (const file of files) {
    const name = file.replace(/\.md$/, "");
    const filePath = path.join(COMMANDS_DIR, file);
    const content = fs.readFileSync(filePath, "utf8");
    const meta = extractCommandMeta(content);

    commands[name] = {
      file: path.relative(ROOT, filePath),
      description: meta.description,
      allowedTools: meta.allowedTools,
    };
  }

  return {
    _generated: new Date().toISOString(),
    _description:
      "KiiPS commands registry. Auto-generated by .claude/scripts/build-registries.js",
    _source:
      ".claude/commands/*.md frontmatter (description) or first H1 fallback",
    commands,
    stats: {
      totalCommands: Object.keys(commands).length,
    },
  };
}

// ─── 메인 ───────────────────────────────────────────────────
function main() {
  const skillsReg = buildSkillsRegistry();
  const commandsReg = buildCommandsRegistry();

  const skillsOut = path.join(ROOT, ".claude/skills-registry.json");
  const commandsOut = path.join(ROOT, ".claude/commands-registry.json");

  fs.writeFileSync(skillsOut, JSON.stringify(skillsReg, null, 2) + "\n");
  fs.writeFileSync(commandsOut, JSON.stringify(commandsReg, null, 2) + "\n");

  console.log(
    "✓ skills-registry.json  — " +
      skillsReg.stats.totalSkills +
      " skills (" +
      "domain:" +
      skillsReg.stats.domain +
      " / common:" +
      skillsReg.stats.common +
      " / design:" +
      skillsReg.stats.design +
      ")",
  );
  console.log(
    "✓ commands-registry.json — " +
      commandsReg.stats.totalCommands +
      " commands",
  );
  console.log("");
  console.log("산출:");
  console.log("  " + path.relative(ROOT, skillsOut));
  console.log("  " + path.relative(ROOT, commandsOut));
}

if (require.main === module) {
  main();
}

module.exports = {
  buildSkillsRegistry,
  buildCommandsRegistry,
  parseFrontmatter,
  extractCommandMeta,
};
